import type { MahjongStats, MahjongRecord } from '../types/mahjong';
import { formatCurrency, formatDate } from './formatters';

export function generateStatsImageCard(stats: MahjongStats, latest?: MahjongRecord, userName: string = '雀神'): Promise<string> {
  return new Promise((resolve) => {
    const canvas = document.createElement('canvas');
    canvas.width = 800;
    canvas.height = 1000;
    const ctx = canvas.getContext('2d')!;

    // 背景漸層
    const gradient = ctx.createLinearGradient(0, 0, 0, 1000);
    gradient.addColorStop(0, '#06130e');
    gradient.addColorStop(0.5, '#0b231a');
    gradient.addColorStop(1, '#05110c');
    ctx.fillStyle = gradient;
    ctx.fillRect(0, 0, 800, 1000);

    // 金色外框與裝飾
    ctx.strokeStyle = '#ca8a04';
    ctx.lineWidth = 4;
    ctx.strokeRect(30, 30, 740, 940);
    ctx.strokeStyle = '#eab308';
    ctx.lineWidth = 1;
    ctx.strokeRect(40, 40, 720, 920);

    // 標題
    ctx.fillStyle = '#facc15';
    ctx.font = 'bold 38px sans-serif';
    ctx.textAlign = 'center';
    ctx.fillText('🀄 台灣麻將個人榮譽戰報', 400, 100);

    ctx.fillStyle = '#94a3b8';
    ctx.font = '20px sans-serif';
    ctx.fillText(`雀士玩家：${userName} · 生成於 ${new Date().toLocaleDateString()}`, 400, 140);

    // 分隔線
    ctx.strokeStyle = '#1f5540';
    ctx.beginPath();
    ctx.moveTo(60, 170);
    ctx.lineTo(740, 170);
    ctx.stroke();

    // 累計淨損益
    ctx.fillStyle = '#94a3b8';
    ctx.font = '22px sans-serif';
    ctx.fillText('生涯總淨損益 (NTD)', 400, 220);

    ctx.fillStyle = stats.totalProfit >= 0 ? '#34d399' : '#f87171';
    ctx.font = 'bold 64px monospace';
    ctx.fillText(formatCurrency(stats.totalProfit), 400, 290);

    // 四格核心數據矩陣
    const drawBox = (x: number, y: number, w: number, h: number, title: string, value: string, color: string) => {
      ctx.fillStyle = '#061a13';
      ctx.fillRect(x, y, w, h);
      ctx.strokeStyle = '#1f5540';
      ctx.strokeRect(x, y, w, h);

      ctx.fillStyle = '#94a3b8';
      ctx.font = '18px sans-serif';
      ctx.textAlign = 'center';
      ctx.fillText(title, x + w / 2, y + 35);

      ctx.fillStyle = color;
      ctx.font = 'bold 28px monospace';
      ctx.fillText(value, x + w / 2, y + 80);
    };

    drawBox(70, 340, 310, 110, '生涯勝率', `${stats.winRate.toFixed(1)}%`, '#facc15');
    drawBox(420, 340, 310, 110, '每將平均期望值 (EV)', `${formatCurrency(Math.round(stats.expectedValuePerRound))}`, stats.expectedValuePerRound >= 0 ? '#34d399' : '#f87171');
    drawBox(70, 480, 310, 110, '總對戰場次 / 將數', `${stats.totalMatches}場 / ${stats.totalRounds}將`, '#e2e8f0');
    drawBox(420, 480, 310, 110, '最高連勝紀錄', `${stats.bestStreak} 連勝`, '#fb923c');

    // 近期戰況
    if (latest) {
      ctx.fillStyle = '#102d22';
      ctx.fillRect(70, 630, 660, 180);
      ctx.strokeStyle = '#27684e';
      ctx.strokeRect(70, 630, 660, 180);

      ctx.fillStyle = '#facc15';
      ctx.font = 'bold 22px sans-serif';
      ctx.textAlign = 'left';
      ctx.fillText(`🎯 最近一把實戰紀錄 (${formatDate(latest.date)})`, 100, 675);

      ctx.fillStyle = '#cbd5e1';
      ctx.font = '18px sans-serif';
      ctx.fillText(`規格：${latest.baseScore}/${latest.pointScore} 底台 · ${latest.rounds}將 · 地點：${latest.location || '現場'}`, 100, 715);
      
      const tagStr = latest.tags.length > 0 ? latest.tags.join('、') : '一般牌型';
      ctx.fillText(`標籤：${tagStr}`, 100, 755);

      ctx.textAlign = 'right';
      ctx.fillStyle = latest.amount >= 0 ? '#34d399' : '#f87171';
      ctx.font = 'bold 36px monospace';
      ctx.fillText(formatCurrency(latest.amount), 700, 730);
    }

    // 底部浮水印
    ctx.fillStyle = '#475569';
    ctx.font = '16px sans-serif';
    ctx.textAlign = 'center';
    ctx.fillText('Generated by Solo Mahjong Ledger · 雲端實戰記帳首選', 400, 920);

    resolve(canvas.toDataURL('image/png'));
  });
}